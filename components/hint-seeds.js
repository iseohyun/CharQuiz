const DAKUTEN = '゙';
const HANDAKUTEN = '゚';
const ROMAJI_BY_BASE_SOUND = { k: 'g', s: 'z', t: 'd', h: 'b' };

/**
 * 기본 힌트 한 줄. 탁점·반탁점 글자는 바탕 글자의 힌트로 만든다.
 * @returns {string|null}
 */
export function getSeedHint(domain, char) {
  const table = BASE_HINTS[domain];
  if (!table || !char) return null;
  if (table[char]) return table[char];

  const decomposed = char.normalize('NFD');
  const base = decomposed[0];
  if (!table[base]) return null;
  const baseRomaji = (table[base].match(/\(([a-z]+)/) || [])[1] || '';
  if (decomposed.includes(HANDAKUTEN)) {
    return `${base}에 반탁점(゜, 동그라미)을 붙이면 p 소리: ${baseRomaji.replace(/^[hf]/, 'p')}.`;
  }
  if (decomposed.includes(DAKUTEN)) {
    const voiced = baseRomaji.replace(/^(ch|sh|ts|[ksthf])/, (m) => ({ ch: 'j', sh: 'j', ts: 'z', f: 'b' }[m] || ROMAJI_BY_BASE_SOUND[m] || m));
    return `${base}에 탁점(゛)을 찍으면 탁한 소리: ${voiced}.`;
  }
  return null;
}
